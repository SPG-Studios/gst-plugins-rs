use gst::glib;
use gst::prelude::*;

mod imp;

glib::wrapper! {
    pub struct Decoder(ObjectSubclass<imp::ImageRsDecoder>) @extends gst::Element, gst::Object;
}

pub fn register(plugin: &gst::Plugin) -> Result<(), glib::BoolError> {
    gst::Element::register(
        Some(plugin),
        "imagersdec",
        gst::Rank::SECONDARY + 1,
        Decoder::static_type(),
    )
}
